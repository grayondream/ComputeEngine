#!/usr/bin/env python3
"""Regenerate tests/data/mlp_reference.h.

The MLP is 4x8 -> 16 -> 8 -> 4 with ReLU/ReLU/Softmax in float32. The golden
header is committed, so the C++ tests never need Python or PyTorch at runtime.

Usage:
    python3 tests/reference/gen_mlp_reference.py
"""

from pathlib import Path

import torch

BATCH = 4
IN = 8
H1 = 16
H2 = 8
OUT = 4
SEED = 20261106

HEADER_PATH = Path(__file__).resolve().parent.parent / "data" / "mlp_reference.h"


def emit_array(lines: list[str], name: str, size_expr: str,
               values: torch.Tensor) -> None:
    flat = values.reshape(-1).tolist()
    lines.append(f"inline constexpr float {name}[{size_expr}] = {{")
    for start in range(0, len(flat), 6):
        chunk = ", ".join(f"{value:.9f}f" for value in flat[start:start + 6])
        lines.append(f"    {chunk},")
    lines.append("};")
    lines.append("")


def main() -> None:
    # Keep the explicit manual seed as documented by the task; the dedicated
    # generator makes the reference independent of global RNG consumption.
    torch.manual_seed(SEED)
    g = torch.Generator().manual_seed(SEED)

    w1 = torch.randn(IN, H1, generator=g) * 0.5
    b1 = torch.randn(H1, generator=g) * 0.1
    w2 = torch.randn(H1, H2, generator=g) * 0.5
    b2 = torch.randn(H2, generator=g) * 0.1
    w3 = torch.randn(H2, OUT, generator=g) * 0.5
    b3 = torch.randn(OUT, generator=g) * 0.1
    x = torch.randn(BATCH, IN, generator=g)

    h1 = torch.relu(x @ w1 + b1)
    h2 = torch.relu(h1 @ w2 + b2)
    probs = torch.softmax(h2 @ w3 + b3, dim=-1)

    assert x.dtype == torch.float32
    assert probs.shape == (BATCH, OUT)

    lines: list[str] = [
        "#pragma once",
        "",
        "// Generated by tests/reference/gen_mlp_reference.py; do not edit by hand.",
        "// PyTorch float32 reference for 4x8 -> 16 -> 8 -> 4 (ReLU/ReLU/Softmax).",
        "// Regenerate with: python3 tests/reference/gen_mlp_reference.py",
        "",
        "namespace ie {",
        "",
        f"inline constexpr int kMlpBatch = {BATCH};",
        f"inline constexpr int kMlpIn = {IN};",
        f"inline constexpr int kMlpH1 = {H1};",
        f"inline constexpr int kMlpH2 = {H2};",
        f"inline constexpr int kMlpOut = {OUT};",
        "",
        "// x: [kMlpBatch, kMlpIn]",
    ]
    emit_array(lines, "kMlpInput", "kMlpBatch * kMlpIn", x)
    lines.append("// W1: [kMlpIn, kMlpH1]")
    emit_array(lines, "kMlpW1", "kMlpIn * kMlpH1", w1)
    lines.append("// b1: [kMlpH1]")
    emit_array(lines, "kMlpB1", "kMlpH1", b1)
    lines.append("// W2: [kMlpH1, kMlpH2]")
    emit_array(lines, "kMlpW2", "kMlpH1 * kMlpH2", w2)
    lines.append("// b2: [kMlpH2]")
    emit_array(lines, "kMlpB2", "kMlpH2", b2)
    lines.append("// W3: [kMlpH2, kMlpOut]")
    emit_array(lines, "kMlpW3", "kMlpH2 * kMlpOut", w3)
    lines.append("// b3: [kMlpOut]")
    emit_array(lines, "kMlpB3", "kMlpOut", b3)
    lines.append("// softmax(h2 @ W3 + b3): [kMlpBatch, kMlpOut]")
    emit_array(lines, "kMlpExpected", "kMlpBatch * kMlpOut", probs)
    lines.append("}  // namespace ie")
    lines.append("")

    HEADER_PATH.parent.mkdir(parents=True, exist_ok=True)
    HEADER_PATH.write_text("\n".join(lines), encoding="ascii")
    print(f"wrote {HEADER_PATH}")


if __name__ == "__main__":
    main()
