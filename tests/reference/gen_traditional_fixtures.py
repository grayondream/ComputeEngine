#!/usr/bin/env python3
"""Regenerate the traditional-op golden fixtures.

Writes tests/data/traditional_reference.h plus the tiny CNN end-to-end fixture
(tests/data/tiny_cnn.onnx and tests/data/tiny_cnn_reference.h). The generated
files are committed, so the C++ tests never need Python, PyTorch, ONNX, or ONNX
Runtime at runtime. Everything here is float32 and generated from an explicit
seeded CPU generator, so reruns are deterministic.

The ONNX export needs the onnx and onnxruntime packages in addition to torch.
On the development machine those are installed in a separate venv:

    PYTHONPATH=/tmp/opencode/onnxvenv/lib/python3.14/site-packages \
        python3 tests/reference/gen_traditional_fixtures.py
"""

from pathlib import Path

import numpy as np
import torch
import torch.nn as nn
import torch.nn.functional as F

SEED = 20261114

DATA_DIR = Path(__file__).resolve().parent.parent / "data"
HEADER_PATH = DATA_DIR / "traditional_reference.h"
TINY_CNN_ONNX_PATH = DATA_DIR / "tiny_cnn.onnx"
TINY_CNN_HEADER_PATH = DATA_DIR / "tiny_cnn_reference.h"

TINY_CNN_INPUT_SHAPE = (1, 3, 8, 8)


def emit_array(lines: list[str], name: str, size: int, values: torch.Tensor) -> None:
    flat = values.reshape(-1).tolist()
    assert len(flat) == size, f"{name}: expected {size}, got {len(flat)}"
    lines.append(f"inline constexpr float {name}[{size}] = {{")
    for start in range(0, len(flat), 6):
        chunk = ", ".join(f"{value:.9f}f" for value in flat[start:start + 6])
        lines.append(f"    {chunk},")
    lines.append("};")
    lines.append("")


class TinyCnn(nn.Module):
    """1x3x8x8 -> Conv -> BatchNorm -> ReLU -> MaxPool -> Conv -> ReLU ->
    GlobalAveragePool -> Flatten -> Gemm -> 1x3 logits."""

    def __init__(self, g: torch.Generator) -> None:
        super().__init__()
        self.conv1 = nn.Conv2d(3, 4, kernel_size=3, padding=1)
        self.bn1 = nn.BatchNorm2d(4)
        self.conv2 = nn.Conv2d(4, 6, kernel_size=3, padding=1)
        self.fc = nn.Linear(6, 3)
        with torch.no_grad():
            self.conv1.weight.copy_(torch.randn(4, 3, 3, 3, generator=g) * 0.3)
            self.conv1.bias.copy_(torch.randn(4, generator=g) * 0.1)
            self.bn1.weight.copy_(torch.randn(4, generator=g) * 0.1 + 1.0)
            self.bn1.bias.copy_(torch.randn(4, generator=g) * 0.05)
            self.bn1.running_mean.copy_(torch.randn(4, generator=g) * 0.1)
            self.bn1.running_var.copy_(
                torch.rand(4, generator=g) * 0.5 + 0.5
            )
            self.bn1.num_batches_tracked.zero_()
            self.conv2.weight.copy_(torch.randn(6, 4, 3, 3, generator=g) * 0.2)
            self.conv2.bias.copy_(torch.randn(6, generator=g) * 0.1)
            self.fc.weight.copy_(torch.randn(3, 6, generator=g) * 0.3)
            self.fc.bias.copy_(torch.randn(3, generator=g) * 0.1)

    def forward(self, x: torch.Tensor) -> torch.Tensor:
        x = F.relu(self.bn1(self.conv1(x)))
        x = F.max_pool2d(x, kernel_size=2, stride=2)
        x = F.relu(self.conv2(x))
        x = F.adaptive_avg_pool2d(x, 1)
        x = torch.flatten(x, 1)
        return self.fc(x)


def generate_tiny_cnn() -> None:
    import onnxruntime as ort  # generation-only dependency

    # Independent stream so the tiny CNN fixture does not move when the
    # traditional-op fixtures above change.
    g = torch.Generator().manual_seed(SEED + 1)
    model = TinyCnn(g).eval()
    x = torch.randn(*TINY_CNN_INPUT_SHAPE, generator=g) * 0.5

    TINY_CNN_ONNX_PATH.parent.mkdir(parents=True, exist_ok=True)
    torch.onnx.export(
        model,
        (x,),
        str(TINY_CNN_ONNX_PATH),
        opset_version=17,
        dynamo=False,
        do_constant_folding=False,
        input_names=["input"],
        output_names=["logits"],
    )

    with torch.no_grad():
        torch_logits = model(x).numpy()

    session = ort.InferenceSession(
        str(TINY_CNN_ONNX_PATH), providers=["CPUExecutionProvider"]
    )
    ort_logits, = session.run(["logits"], {"input": x.numpy()})
    np.testing.assert_allclose(ort_logits, torch_logits, rtol=1e-5, atol=1e-5)
    assert ort_logits.shape == (1, 3), ort_logits.shape

    lines: list[str] = [
        "#pragma once",
        "",
        "// Generated by tests/reference/gen_traditional_fixtures.py;",
        "// do not edit by hand.",
        "// Deterministic input and ONNX Runtime logits for tiny_cnn.onnx.",
        "// Regenerate with the command in the generator header.",
        "",
        "namespace ie {",
        "",
        "// Tiny CNN input: [1, 3, 8, 8]",
    ]
    emit_array(lines, "kTinyCnnInput", 1 * 3 * 8 * 8, x)
    lines.append("// ONNX Runtime logits: [1, 3]")
    emit_array(lines, "kTinyCnnExpected", 3, torch.from_numpy(ort_logits))
    lines.append("}  // namespace ie")
    lines.append("")

    TINY_CNN_HEADER_PATH.write_text("\n".join(lines), encoding="ascii")
    print(f"wrote {TINY_CNN_ONNX_PATH}")
    print(f"wrote {TINY_CNN_HEADER_PATH}")


def main() -> None:
    g = torch.Generator().manual_seed(SEED)

    # Conv2D: x [1,2,5,5], w [3,2,3,3], b [3], stride 1, pads 1 -> [1,3,5,5].
    conv_x = torch.randn(1, 2, 5, 5, generator=g) * 0.5
    conv_w = torch.randn(3, 2, 3, 3, generator=g) * 0.5
    conv_b = torch.randn(3, generator=g) * 0.25
    conv_y = F.conv2d(conv_x, conv_w, conv_b, stride=1, padding=1)
    assert conv_x.dtype == torch.float32
    assert conv_y.shape == (1, 3, 5, 5)

    # BatchNorm: x [1,3,2,2], params [3], epsilon 1e-5.
    bn_x = torch.randn(1, 3, 2, 2, generator=g)
    bn_scale = torch.randn(3, generator=g) * 0.5 + 1.0
    bn_bias = torch.randn(3, generator=g) * 0.25
    bn_mean = torch.randn(3, generator=g) * 0.25
    bn_var = torch.rand(3, generator=g) * 1.5 + 0.25
    bn_y = F.batch_norm(
        bn_x, bn_mean, bn_var, bn_scale, bn_bias, training=False, eps=1e-5
    )
    assert bn_y.shape == (1, 3, 2, 2)

    # MaxPool/AvgPool: x [1,2,4,4], kernel 2x2, stride 2 -> [1,2,2,2].
    pool_x = torch.randn(1, 2, 4, 4, generator=g)
    max_y = F.max_pool2d(pool_x, kernel_size=2, stride=2)
    avg_y = F.avg_pool2d(pool_x, kernel_size=2, stride=2)
    assert max_y.shape == (1, 2, 2, 2)
    assert avg_y.shape == (1, 2, 2, 2)

    # GlobalAvgPool: x [1,2,3,2] -> [1,2,1,1].
    ga_x = torch.randn(1, 2, 3, 2, generator=g)
    ga_y = ga_x.mean(dim=(2, 3), keepdim=True)
    assert ga_y.shape == (1, 2, 1, 1)

    # DepthwiseConv2D: x [1,2,3,3], w [2,1,2,2], b [2], groups=2 -> [1,2,2,2].
    dw_x = torch.randn(1, 2, 3, 3, generator=g)
    dw_w = torch.randn(2, 1, 2, 2, generator=g) * 0.5
    dw_b = torch.randn(2, generator=g) * 0.25
    dw_y = F.conv2d(dw_x, dw_w, dw_b, stride=1, groups=2)
    assert dw_y.shape == (1, 2, 2, 2)

    lines: list[str] = [
        "#pragma once",
        "",
        "// Generated by tests/reference/gen_traditional_fixtures.py;",
        "// do not edit by hand.",
        "// PyTorch float32 reference for Conv2D, BatchNorm, pooling, and",
        "// GlobalAvgPool. Regenerate with:",
        "//   python3 tests/reference/gen_traditional_fixtures.py",
        "",
        "namespace ie {",
        "",
        "// Conv2D input: [1, 2, 5, 5]",
    ]
    emit_array(lines, "kConvInput", 50, conv_x)
    lines.append("// Conv2D weight: [3, 2, 3, 3]")
    emit_array(lines, "kConvWeight", 54, conv_w)
    lines.append("// Conv2D bias: [3]")
    emit_array(lines, "kConvBias", 3, conv_b)
    lines.append("// conv2d(pad=1): [1, 3, 5, 5]")
    emit_array(lines, "kConvExpected", 75, conv_y)

    lines.append("// BatchNorm input: [1, 3, 2, 2]")
    emit_array(lines, "kBatchNormInput", 12, bn_x)
    lines.append("// BatchNorm scale: [3]")
    emit_array(lines, "kBatchNormScale", 3, bn_scale)
    lines.append("// BatchNorm bias: [3]")
    emit_array(lines, "kBatchNormBias", 3, bn_bias)
    lines.append("// BatchNorm mean: [3]")
    emit_array(lines, "kBatchNormMean", 3, bn_mean)
    lines.append("// BatchNorm var: [3]")
    emit_array(lines, "kBatchNormVar", 3, bn_var)
    lines.append("// batch_norm(eps=1e-5): [1, 3, 2, 2]")
    emit_array(lines, "kBatchNormExpected", 12, bn_y)

    lines.append("// Pool input: [1, 2, 4, 4]")
    emit_array(lines, "kPoolInput", 32, pool_x)
    lines.append("// max_pool2d(k=2, s=2): [1, 2, 2, 2]")
    emit_array(lines, "kMaxPoolExpected", 8, max_y)
    lines.append("// avg_pool2d(k=2, s=2): [1, 2, 2, 2]")
    emit_array(lines, "kAvgPoolExpected", 8, avg_y)

    lines.append("// GlobalAvgPool input: [1, 2, 3, 2]")
    emit_array(lines, "kGlobalAvgInput", 12, ga_x)
    lines.append("// mean over HxW: [1, 2, 1, 1]")
    emit_array(lines, "kGlobalAvgExpected", 2, ga_y)

    lines.append("// DepthwiseConv2D input: [1, 2, 3, 3]")
    emit_array(lines, "kDepthwiseInput", 18, dw_x)
    lines.append("// DepthwiseConv2D weight: [2, 1, 2, 2]")
    emit_array(lines, "kDepthwiseWeight", 8, dw_w)
    lines.append("// DepthwiseConv2D bias: [2]")
    emit_array(lines, "kDepthwiseBias", 2, dw_b)
    lines.append("// conv2d(groups=2): [1, 2, 2, 2]")
    emit_array(lines, "kDepthwiseExpected", 8, dw_y)

    lines.append("}  // namespace ie")
    lines.append("")

    HEADER_PATH.parent.mkdir(parents=True, exist_ok=True)
    HEADER_PATH.write_text("\n".join(lines), encoding="ascii")
    print(f"wrote {HEADER_PATH}")

    generate_tiny_cnn()


if __name__ == "__main__":
    main()
