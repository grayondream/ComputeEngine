using namespace ie;

namespace {

constexpr std::size_t kResNet50InputElements = 1 * 3 * 224 * 224;
constexpr std::size_t kResNet50Logits = 1000;

Tensor make_tensor(const Shape& shape, std::span<const float> values) {
    auto alloc = std::make_shared<MallocAllocator>();
    auto tensor = Tensor::allocate(shape, DType::F32, alloc);
    EXPECT_TRUE(tensor.has_value());
    Tensor result = std::move(*tensor);
    std::copy(values.begin(), values.end(), result.data<float>());
    return result;
}

std::size_t argmax(std::span<const float> values) {
    return static_cast<std::size_t>(
        std::distance(values.begin(),
                      std::max_element(values.begin(), values.end())));
}

// Reads exactly 1000 little-endian float32 logits; an empty vector means the
// file is missing, short, or has trailing bytes.
std::vector<float> read_float_binary(const std::string& path) {
    std::ifstream file(path, std::ios::binary);
    if (!file) {
        return {};
    }
    std::vector<float> values(kResNet50Logits);
    file.read(reinterpret_cast<char*>(values.data()),
              static_cast<std::streamsize>(values.size() * sizeof(float)));
    if (!file) {
        return {};
    }
    if (file.peek() != std::char_traits<char>::eof()) {
        return {};
    }
    return values;
}

}  // namespace

// Local verification against a real ResNet50 exported from torchvision and run
// by ONNX Runtime. Both files are generated by
// tests/reference/gen_resnet50_onnx.py; the ~100 MB ONNX is never committed, so
// the test skips when the environment variables are absent.
TEST(ResNet50ParityTest, MatchesOnnxRuntimeReference) {
    const char* onnx_path = std::getenv("IE_RESNET50_ONNX");
    const char* reference_path = std::getenv("IE_RESNET50_REFERENCE");
    if (onnx_path == nullptr || reference_path == nullptr) {
        GTEST_SKIP() << "set IE_RESNET50_ONNX and IE_RESNET50_REFERENCE";
    }

    const std::vector<float> expected = read_float_binary(reference_path);
    ASSERT_EQ(expected.size(), kResNet50Logits)
        << "cannot read 1000 float32 logits from " << reference_path;

    TraditionalEngine engine;
    auto loaded = engine.load_model(onnx_path, ModelFormat::ONNX);
    ASSERT_TRUE(loaded.has_value()) << loaded.error().message;

    const std::vector<float> ones(kResNet50InputElements, 1.0f);
    auto input = make_tensor(Shape{{1, 3, 224, 224}}, ones);

    const auto start = std::chrono::steady_clock::now();
    auto out = engine.infer({input});
    const double elapsed = std::chrono::duration<double>(
                               std::chrono::steady_clock::now() - start)
                               .count();
    ASSERT_TRUE(out.has_value()) << out.error().message;
    std::cout << "[ resnet50 ] CPU forward: " << elapsed << " s\n";

    ASSERT_EQ(out->numel(), static_cast<int64_t>(kResNet50Logits));
    const std::span<const float> actual(out->data<float>(), kResNet50Logits);

    float max_err = 0.0f;
    std::size_t worst = 0;
    for (std::size_t i = 0; i < kResNet50Logits; ++i) {
        const float err = std::abs(actual[i] - expected[i]);
        if (err > max_err) {
            max_err = err;
            worst = i;
        }
    }
    std::cout << "[ resnet50 ] max abs error: " << max_err << " at logit "
              << worst << "\n";
    std::cout << "[ resnet50 ] argmax: engine " << argmax(actual) << ", onnxruntime "
              << argmax(expected) << "\n";

    EXPECT_LT(max_err, 1e-3f);
    EXPECT_EQ(argmax(actual), argmax(expected));
}
